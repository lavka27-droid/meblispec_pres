let currentLang = localStorage.getItem('pres-lang') || 'uk';

window.t = function(key) {
  if (currentLang === 'uk') return key;
  return DICT_EN[key] || key;
};

window.setLang = function(lang) {
  currentLang = lang;
  localStorage.setItem('pres-lang', lang);
  translateDOM(document.body);
  
  // Custom updates
  document.querySelectorAll('.lang-btn').forEach(b => b.classList.remove('active'));
  let btn = document.getElementById('lang-btn-' + lang);
  if(btn) btn.classList.add('active');

  // Trigger UI refresh if needed
  if(typeof updateStamp === 'function') updateStamp();
  if(typeof pUpdateGlobalText === 'function') pUpdateGlobalText();
  if(typeof loadPresetsUI === 'function') loadPresetsUI();
};

function translateDOM(root) {
  const isEN = (currentLang === 'en');
  
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null, false);
  const textNodes = [];
  while(walker.nextNode()) {
    textNodes.push(walker.currentNode);
  }
  
  textNodes.forEach(node => {
    let parent = node.parentElement;
    if(!parent || parent.tagName === 'SCRIPT' || parent.tagName === 'STYLE') return;
    
    // Store original text
    if (typeof node._origText === 'undefined') {
      let val = node.nodeValue.trim();
      if(val.length > 0) {
        node._origText = node.nodeValue;
      } else {
        node._origText = null;
      }
    }
    
    let orig = node._origText;
    if (orig) {
       let trimmed = orig.trim();
       if (DICT_EN[trimmed]) {
         node.nodeValue = orig.replace(trimmed, isEN ? DICT_EN[trimmed] : trimmed);
       } else {
         // Try to find any known key as substring
         let newVal = orig;
         for (let k in DICT_EN) {
           if (k.length < 4) continue; // build90: короткі ключі ("і", "мм", "П1") — лише точний збіг, інакше калічать довільний текст
           if (newVal.includes(k)) {
             newVal = newVal.replace(k, isEN ? DICT_EN[k] : k);
           }
         }
         node.nodeValue = newVal;
       }
    }
  });

  // Translate attributes: title, placeholder
  root.querySelectorAll('[title]').forEach(el => {
    if (!el.hasAttribute('data-orig-title')) el.setAttribute('data-orig-title', el.getAttribute('title'));
    let orig = el.getAttribute('data-orig-title');
    el.setAttribute('title', isEN ? (DICT_EN[orig] || orig) : orig);
  });

  root.querySelectorAll('[placeholder]').forEach(el => {
    if (!el.hasAttribute('data-orig-placeholder')) el.setAttribute('data-orig-placeholder', el.getAttribute('placeholder'));
    let orig = el.getAttribute('data-orig-placeholder');
    el.setAttribute('placeholder', isEN ? (DICT_EN[orig] || orig) : orig);
  });
}

