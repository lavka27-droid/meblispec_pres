// Override globals for automatic translation
const origAlert = window.alert;
window.alert = function(msg) {
  let translatedMsg = msg;
  if (typeof msg === 'string') {
    let tMsg = window.t(msg);
    if (tMsg === msg) {
      const prefixes = ["Помилка при створенні PDF: ", "Помилка завантаження: ", "Не вдалося завантажити бібліотеки PDF: ", "Помилка зв'язку з Ruby."];
      for(let p of prefixes) {
        if(msg.startsWith(p)) {
          translatedMsg = window.t(p) + msg.substring(p.length);
          break;
        }
      }
    } else {
      translatedMsg = tMsg;
    }
  }
  origAlert(translatedMsg);
};

const origConfirm = window.confirm;
window.confirm = function(msg) {
  let translatedMsg = msg;
  if (typeof msg === 'string') {
    let tMsg = window.t(msg);
    if (tMsg === msg) {
      // build86: гілку «Видалити шаблон сторінки» прибрано — пресети сторінки видалені з UI
      if (msg.includes('Видалити шаблон проекту')) {
        let name = msg.replace('Видалити шаблон проекту "', '').replace('"?', '');
        translatedMsg = currentLang === 'en' ? `Delete project preset "${name}"?` : msg;
      }
    } else {
      translatedMsg = tMsg;
    }
  }
  return origConfirm(translatedMsg);
};

const origPrompt = window.prompt;
window.prompt = function(msg, def) {
  return origPrompt(window.t(msg), window.t(def));
};
